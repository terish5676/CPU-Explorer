import { Link, createFileRoute } from "@tanstack/react-router";
import { useEffect, useMemo, useState } from "react";
import { ArrowUpRight } from "lucide-react";
import { simulateCache, parseTrace, SAMPLE_TRACES } from "@/lib/cache-sim";
import {
  simulatePipeline,
  parseProgram,
  SAMPLE_PROGRAMS,
  stageAt,
  STAGES,
} from "@/lib/pipeline-sim";
import { NAV } from "@/components/app-shell";
import { DataBadge } from "@/components/page-header";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/")({
  head: () => ({
    meta: [
      { title: "CPU Performance Explorer — Index" },
      {
        name: "description",
        content:
          "Cache, pipeline and memory-locality simulators with a transparent bottleneck analyser.",
      },
    ],
  }),
  component: Overview,
});

const TOOLS: Record<string, string> = {
  "/code-lab":
    "Run JavaScript for real in a sandbox, replay C/C++/Python/Java examples, and read static loop analysis.",
  "/cache": "Set-associative cache. Scrub through every access and watch sets fill, hit and evict.",
  "/pipeline":
    "Five-stage in-order pipeline with a playhead: forwarding, load-use, branch and port hazards.",
  "/memory": "Generate or paste address traces. Measure stride, spatial and temporal locality.",
  "/assembly": "Classify x86 / RISC listings into arithmetic, memory, control and logic.",
  "/monitor": "Chart any metric across every saved run.",
  "/analysis": "Rule engine that diffs two runs and names the bottleneck — with its evidence.",
  "/runs": "Rename, export, import and prune your saved runs.",
  "/about": "What is modelled, what is measured, how to read every number.",
};

function HeroPipeline() {
  const res = useMemo(
    () =>
      simulatePipeline(parseProgram(SAMPLE_PROGRAMS["raw"]!.text), {
        forwarding: false,
        singleMemoryPort: false,
        maxDynamic: 64,
      }),
    [],
  );
  const [t, setT] = useState(1);
  useEffect(() => {
    const id = setInterval(() => setT((c) => (c >= res.totalCycles + 3 ? 1 : c + 1)), 380);
    return () => clearInterval(id);
  }, [res.totalCycles]);
  const stageClass: Record<string, string> = {
    IF: "bg-stage-if",
    ID: "bg-stage-id",
    EX: "bg-stage-ex",
    MEM: "bg-stage-mem",
    WB: "bg-stage-wb",
  };
  return (
    <div
      className="panel panel-tick p-4"
      aria-label="Live pipeline diagram generated by the simulator"
    >
      <div className="flex items-baseline justify-between">
        <p className="label-mono">Live · RAW chain, forwarding off</p>
        <p className="font-mono text-xs tabular-nums">
          cycle{" "}
          <span className="text-signal">
            {String(Math.min(t, res.totalCycles)).padStart(2, "0")}
          </span>
          /{res.totalCycles}
        </p>
      </div>
      <div className="mt-4 space-y-[3px]">
        {res.dyn.map((d) => (
          <div key={d.seq} className="flex items-center gap-3">
            <span className="w-28 shrink-0 truncate font-mono text-[11px] text-ink-3">
              {d.instr.text.split("#")[0]}
            </span>
            <div
              className="grid flex-1 gap-[2px]"
              style={{ gridTemplateColumns: `repeat(${res.totalCycles}, minmax(0,1fr))` }}
            >
              {Array.from({ length: res.totalCycles }, (_, c) => {
                const occ = stageAt(d, c + 1);
                const on = occ && c + 1 <= t;
                return (
                  <div
                    key={c}
                    className={cn(
                      "h-3.5 transition-all duration-300",
                      on ? stageClass[occ.stage] : occ ? "bg-rule-soft" : "",
                      on && occ?.stalled && "hatch",
                      c + 1 === t && "outline outline-1 outline-offset-1 outline-signal",
                    )}
                    style={!occ ? { background: "transparent" } : undefined}
                  />
                );
              })}
            </div>
          </div>
        ))}
      </div>
      <div className="mt-3 flex gap-3 font-mono text-[10px] uppercase text-ink-3">
        {STAGES.map((s) => (
          <span key={s} className="flex items-center gap-1">
            <i className={cn("inline-block h-2 w-2", stageClass[s])} />
            {s}
          </span>
        ))}
      </div>
    </div>
  );
}

function Overview() {
  const cache = simulateCache(
    { cacheSize: 256, blockSize: 16, ways: 1, policy: "LRU", seed: 1 },
    parseTrace(SAMPLE_TRACES["sequential"]!.text).entries,
  );
  const parsed = parseProgram(SAMPLE_PROGRAMS["raw"]!.text);
  const on = simulatePipeline(parsed, {
    forwarding: true,
    singleMemoryPort: false,
    maxDynamic: 64,
  });
  const off = simulatePipeline(parsed, {
    forwarding: false,
    singleMemoryPort: false,
    maxDynamic: 64,
  });
  const kpis = [
    {
      label: "Hit ratio · sequential walk",
      value: `${((cache.hits / cache.accesses.length) * 100).toFixed(0)}`,
      unit: "%",
      note: "256 B direct-mapped",
    },
    {
      label: "CPI · forwarding on",
      value: on.cpi.toFixed(2),
      unit: "",
      note: `${on.totalCycles} cycles`,
    },
    {
      label: "CPI · forwarding off",
      value: off.cpi.toFixed(2),
      unit: "",
      note: `${off.totalCycles} cycles`,
    },
    {
      label: "Stalls removed by bypass",
      value: String(off.stallCycles.total - on.stallCycles.total),
      unit: "cyc",
      note: "same program, one switch",
    },
  ];

  return (
    <div>
      <section className="rise grid gap-10 pb-12 pt-12 lg:grid-cols-[1.15fr_1fr] lg:items-end">
        <div>
          <p className="label-mono">Computer organisation &amp; architecture · lab instrument</p>
          <h1 className="mt-4 text-[clamp(3.6rem,10.5vw,9.5rem)] leading-[0.86]">
            Where did the <em className="text-signal">cycles</em> go?
          </h1>
          <p className="mt-10 max-w-xl text-[15px] leading-relaxed text-ink-2">
            Feed it an address trace or a tiny program. Watch the cache fill and the pipeline stall,
            one cycle at a time — then let a rule engine, whose every threshold is printed, tell you
            what the bottleneck was.
          </p>
          <div className="mt-6 flex flex-wrap items-center gap-3">
            <Link to="/code-lab" className="btn">
              Live Code Lab <ArrowUpRight />
            </Link>
            <Link to="/cache" className="btn btn-ghost">
              Cache simulator
            </Link>
            <Link to="/pipeline" className="btn btn-ghost">
              Pipeline
            </Link>
            <DataBadge source="Simulated" />
          </div>
        </div>
        <HeroPipeline />
      </section>

      <section className="grid border-y border-rule sm:grid-cols-2 lg:grid-cols-4">
        {kpis.map((k, i) => (
          <div
            key={k.label}
            className={cn(
              "rise p-5",
              i > 0 && "lg:border-l lg:border-rule",
              i % 2 === 1 && "sm:border-l sm:border-rule lg:border-l",
            )}
            style={{ animationDelay: `${i * 70}ms` }}
          >
            <p className="label-mono">{k.label}</p>
            <p className="numeral mt-3 text-[5.5rem]">
              {k.value}
              <span className="ml-1 text-3xl text-signal">{k.unit}</span>
            </p>
            <p className="mt-2 font-mono text-[11px] text-ink-3">{k.note}</p>
          </div>
        ))}
      </section>

      <section className="pt-14">
        <div className="flex items-baseline justify-between">
          <h2 className="text-5xl">Instruments</h2>
          <p className="label-mono">{NAV.length - 1} stations</p>
        </div>
        <ol className="mt-6 border-t border-rule">
          {NAV.filter((n) => n.to !== "/").map((n, i) => (
            <li key={n.to} className="border-b border-rule">
              <Link
                to={n.to}
                className="group relative grid grid-cols-[3rem_1fr_auto] items-baseline gap-4 overflow-hidden py-5 sm:grid-cols-[4rem_14rem_1fr_auto]"
              >
                <span
                  className="absolute inset-0 -translate-x-full bg-signal transition-transform duration-300 ease-out group-hover:translate-x-0"
                  aria-hidden
                />
                <span className="relative font-mono text-xs text-ink-3 transition-colors group-hover:text-signal-ink">
                  {String(i + 1).padStart(2, "0")}
                </span>
                <span className="relative font-display text-4xl leading-none transition-all group-hover:translate-x-2 group-hover:text-signal-ink">
                  {n.label}
                </span>
                <span className="relative hidden max-w-xl text-sm text-ink-2 transition-colors group-hover:text-signal-ink sm:block">
                  {TOOLS[n.to]}
                </span>
                <ArrowUpRight className="relative h-5 w-5 transition-all group-hover:rotate-12 group-hover:text-signal-ink" />
              </Link>
            </li>
          ))}
        </ol>
      </section>
    </div>
  );
}
